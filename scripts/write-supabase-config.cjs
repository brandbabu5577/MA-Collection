// Writes frontend/js/supabase-config.js from environment variables at build/deploy time,
// so the real project URL and publishable key never need to be committed.
//   SUPABASE_URL=https://<ref>.supabase.co SUPABASE_PUBLISHABLE_KEY=sb_publishable_... node scripts/write-supabase-config.cjs
// Refuses service-role / secret keys.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const url = String(process.env.SUPABASE_URL || "").trim();
const key = String(process.env.SUPABASE_PUBLISHABLE_KEY || process.env.SUPABASE_ANON_KEY || "").trim();
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/.test(url)) { console.error("SUPABASE_URL must look like https://<project-ref>.supabase.co"); process.exit(1); }
if (!key) { console.error("SUPABASE_PUBLISHABLE_KEY is required"); process.exit(1); }
if (/^sb_secret_/.test(key) || /service_role/.test(Buffer.from((key.split(".")[1] || ""), "base64").toString())) {
  console.error("Refusing a secret / service-role key. Use the publishable (anon) key only."); process.exit(1);
}
const out = `// Generated by scripts/write-supabase-config.cjs. Publishable key only.\nconst supabaseConfig = {\n  url: ${JSON.stringify(url.replace(/\/$/, ""))},\n  anonKey: ${JSON.stringify(key)}\n};\n\nexport default supabaseConfig;\n`;
fs.writeFileSync(path.join(__dirname, "..", "frontend", "js", "supabase-config.js"), out);
console.log("Wrote frontend/js/supabase-config.js for", url);
